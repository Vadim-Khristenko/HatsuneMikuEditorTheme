// Writes mangadex/README.md: one MangaDex theme link per look.
//
//   bun tools/mangadex/build.ts           write it
//   bun tools/mangadex/build.ts --check   fail if the file on disk is out of date
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { LOOKS } from "../palette/looks";
import { link, themeOf } from "./mangadex";

const ROOT = join(import.meta.dir, "..", "..");
const OUT = join(ROOT, "mangadex", "README.md");

/** The steps that keep a theme, with the screenshot of each in mangadex/howto/. */
const STEPS: [string, string][] = [
  ["1. Open the link for your look. The site turns into it right away, but only for now.", "1-page"],
  ["2. Tap your avatar in the top right corner, then **Theme**.", "2-menu"],
  ["3. Tap the gear next to **Custom**. On a phone, tap the dark area on the left to close the menu.", "3-theme"],
  ["4. The Theme Builder shows the look from the link. Tap **Save theme**.", "4-builder"],
  ["5. MangaDex says the theme has been saved. It stays from now on.", "5-saved"],
];

export function readme(): string {
  const rows = LOOKS.map((l) => {
    const t = themeOf(l);
    return `| ${l.title} | \`${t.colors[1]}\` / \`${t.colors[26]}\` | [Open in MangaDex](${link(t)}) |`;
  });
  return [
    "# Hatsune Miku for MangaDex",
    "",
    "MangaDex keeps a custom theme in a link. Opening one puts the theme on for now; four taps make it stay.",
    "",
    "| Look | Background / Primary | Link |",
    "|---|---|---|",
    ...rows,
    "",
    "## Keep the theme",
    "",
    "The same steps on a computer and on a phone. The pictures show Hatsune Miku Light on a computer and Hatsune Miku Dark on a phone; the pink frame marks what to tap.",
    "",
    "| Step | Computer | Phone |",
    "|---|---|---|",
    ...STEPS.map(([text, shot]) => `| ${text} | ![](howto/pc-${shot}.png) | ![](howto/phone-${shot}.png) |`),
    "",
    "Open the Theme Builder this way, from the page the link opened. Going to mangadex.org/theme directly shows the theme you saved before, not the one from the link, and Save theme stays grey.",
    "",
    "To go back to a built-in theme, open the avatar menu, Theme, and pick Light, Dark or another one. Your saved theme stays under Custom.",
    "",
    "The links are generated from the palette by `bun tools/mangadex/build.ts`. Do not edit this file by hand.",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const text = readme();
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
      console.error("FAIL mangadex/README.md is out of date: bun tools/mangadex/build.ts");
      process.exit(1);
    }
    console.log("mangadex links are up to date");
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${LOOKS.length} MangaDex links`);
  }
}
